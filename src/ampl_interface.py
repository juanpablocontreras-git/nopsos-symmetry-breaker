def save_results_csv(results: List[ExperimentResult], csv_path: str):
    import csv
    results = [r for r in results if r.status not in CSV_EXCLUDED_STATUSES]
    if not results:
        print(f"[CSV] skipped {csv_path} (no successful solve results)")
        return
    file_exists = os.path.exists(csv_path)
    with open(csv_path, "a", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(results[0].to_dict().keys()))
        if not file_exists:
            writer.writeheader()
        for r in results:
            writer.writerow(r.to_dict())
    print(f"[CSV] {csv_path}")
