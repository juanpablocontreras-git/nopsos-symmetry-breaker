"""
AMPL data file generation and experiment runner for NOPSOS experiments.

Two main workflows
------------------
1. General NOPSOS (core + SBS only):
      write_nopsos_dat()  ->  run_ampl()

2. Crude-oil full model (core + SBS + operational layer, MILP by default):
      crude_oil_ampl.write_crude_oil_dat()  ->  run_crude_oil_experiment()
"""

import os
import re
import subprocess
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from .dfa_builder import DFA


