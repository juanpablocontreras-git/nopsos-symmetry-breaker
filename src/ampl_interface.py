# Main crude-oil MILP experiment runner
# ---------------------------------------------------------------------------

def run_crude_oil_experiment(
    instance_name: str,
    formulation: str,
    mod_path: str,
    dat_path: str,
    dfa: DFA,
    W: List[str],
    n_slots: int,
    results_dir: str = "results",
    ampl_exe: str = "ampl",
    nlp_solver: str = "ipopt",
    milp_time_limit: int = 3600,
    nlp_time_limit: int = 600,
    mip_gap: float = 1e-4,
    threads: int = 1,
    run_nlp: bool = False,
    disable_sbs: bool = False,
    extra_gurobi_opts: str = "",
    objective_name: str = "GrossMargin",
) -> ExperimentResult:
    """
    Run the crude-oil MILP on a crude-oil instance.

    By default this solves only the MILP obtained by dropping
    CompositionBilinear. Set run_nlp=True to run the older second-stage NLP
    workflow without deleting the nonlinear model.

    Returns
    -------
    ExperimentResult with MILP fields populated.
    """
    os.makedirs(results_dir, exist_ok=True)
    tag = f"{instance_name}_{formulation}".replace("+", "_").replace(" ", "_")

    milp_run  = os.path.join(results_dir, f"{tag}_milp.run")
    sol_file  = os.path.join(results_dir, f"{tag}.sol")
    milp_log  = os.path.join(results_dir, f"{tag}_gurobi.log")
    milp_out  = os.path.join(results_dir, f"{tag}_milp.out")
    for stale_path in (milp_log, milp_out):
        if os.path.exists(stale_path):
            os.remove(stale_path)

    write_milp_run_script(milp_run, mod_path, dat_path, sol_file, milp_log,
                          milp_time_limit, mip_gap, threads,
                          extra_gurobi_opts=extra_gurobi_opts,
                          write_solution=run_nlp,
                          disable_sbs=disable_sbs,
                          objective_name=objective_name)

    # ── MILP step ────────────────────────────────────────────────────────────
    print(f"[MILP] {formulation} on {instance_name} ...")
    t0 = time.perf_counter()
    try:
        proc = subprocess.run(
            [ampl_exe, milp_run],
            capture_output=True, text=True,
            timeout=milp_time_limit + 120,
        )
        milp_wall = time.perf_counter() - t0
        milp_stdout = proc.stdout + proc.stderr
        milp_returncode = proc.returncode
    except subprocess.TimeoutExpired:
        milp_wall = time.perf_counter() - t0
        milp_stdout = "TIMEOUT"
        milp_returncode = None

    with open(milp_out, "w") as fh:
        fh.write(milp_stdout)

    milp_parsed = parse_ampl_output(milp_stdout, "MILP_RESULT")
    milp_failure = None if milp_parsed.get("status") else classify_ampl_failure(
        milp_stdout, milp_returncode
    )
    if milp_failure:
        milp_parsed["status"] = milp_failure
    gurobi_info = parse_gurobi_log(milp_log)
    milp_time   = milp_parsed.get("solve_time") or milp_wall

    print(f"  MILP: status={milp_parsed['status']}  "
          f"obj={milp_parsed['obj']}  time={milp_time:.1f}s  "
          f"nodes={gurobi_info.get('n_nodes')}")

    # ── NLP step (only if MILP found a feasible solution) ────────────────────
    nlp_time = None
    nlp_obj  = None
    nlp_status = "skipped"

    milp_feasible = (
        milp_parsed.get("status", "") in ("solved", "feasible", "optimal")
        and os.path.exists(sol_file)
    )

    if run_nlp and milp_feasible:
        nlp_run   = os.path.join(results_dir, f"{tag}_nlp.run")
        nlp_out   = os.path.join(results_dir, f"{tag}_nlp.out")
        nlp_log   = os.path.join(results_dir, f"{tag}_nlp.log")
        write_nlp_run_script(nlp_run, mod_path, dat_path, sol_file, nlp_log,
                             nlp_solver, nlp_time_limit)

        print(f"[NLP]  {formulation} on {instance_name} ...")
        t1 = time.perf_counter()
        try:
            proc2 = subprocess.run(
                [ampl_exe, nlp_run],
                capture_output=True, text=True,
                timeout=nlp_time_limit + 60,
            )
            nlp_wall = time.perf_counter() - t1
            nlp_stdout = proc2.stdout + proc2.stderr
            nlp_returncode = proc2.returncode
        except subprocess.TimeoutExpired:
            nlp_wall = time.perf_counter() - t1
            nlp_stdout = "TIMEOUT"
            nlp_returncode = None

        with open(nlp_out, "w") as fh:
            fh.write(nlp_stdout)

        nlp_parsed = parse_ampl_output(nlp_stdout, "NLP_RESULT")
        nlp_failure = None if nlp_parsed.get("status") else classify_ampl_failure(
            nlp_stdout, nlp_returncode
        )
        if nlp_failure:
            nlp_parsed["status"] = nlp_failure
        nlp_time   = nlp_parsed.get("solve_time") or nlp_wall
        nlp_obj    = nlp_parsed.get("obj")
        nlp_status = nlp_parsed.get("status") or "ampl_error"
        print(f"  NLP:  status={nlp_status}  obj={nlp_obj}  time={nlp_time:.1f}s")

    # Compute final gap between MILP upper bound and NLP lower bound
    milp_ub = milp_parsed.get("obj")
    gap = None
    if milp_ub is not None and nlp_obj is not None and milp_ub > 0:
        gap = abs(milp_ub - nlp_obj) / abs(milp_ub)

    n_Z = n_slots * len(W)
    n_f = n_slots * dfa.n_arcs

    return ExperimentResult(
        instance_name=instance_name,
        formulation=formulation,
        n_ops=len(W),
        n_slots=n_slots,
        n_dfa_states=dfa.n_states,
        n_dfa_arcs=dfa.n_arcs,
        n_binary_vars=n_Z + n_f,
        n_constraints=milp_parsed.get("n_cons") or 0,
        obj_value=nlp_obj if run_nlp and nlp_obj is not None else milp_ub,
        best_bound=gurobi_info.get("best_bound"),
        gap=gap if gap is not None else gurobi_info.get("gap"),
        milp_time=milp_time,
        nlp_time=nlp_time,
        total_time=(milp_time or 0) + ((nlp_time or 0) if run_nlp else 0),
        n_nodes=gurobi_info.get("n_nodes"),
        status=nlp_status if run_nlp and milp_feasible else (milp_parsed.get("status") or "ampl_error"),
        n_variables=milp_parsed.get("n_vars"),
    )


# ---------------------------------------------------------------------------
# Simpler runner for core-only experiments (no operational layer)
# ---------------------------------------------------------------------------

def run_ampl(
    instance_name: str,
    formulation: str,
    mod_path: str,
    dat_path: str,
    dfa: DFA,
    W: List[str],
    n_slots: int,
    results_dir: str = "results",
    ampl_exe: str = "ampl",
    time_limit: int = 3600,
    mip_gap: float = 1e-4,
    threads: int = 1,
) -> ExperimentResult:
    """Single-step MILP solve (for models without bilinear composition)."""
    os.makedirs(results_dir, exist_ok=True)
    tag = f"{instance_name}_{formulation}".replace("+", "_").replace(" ", "_")
    run_path = os.path.join(results_dir, f"{tag}.run")
    log_path = os.path.join(results_dir, f"{tag}_gurobi.log")
    out_path = os.path.join(results_dir, f"{tag}.out")
    sol_path = os.path.join(results_dir, f"{tag}.sol")
    for stale_path in (log_path, out_path):
        if os.path.exists(stale_path):
            os.remove(stale_path)

    log_path_opt = log_path.replace("\\", "/")
    gurobi_opts = (
        f"timelimit={time_limit} mipgap={mip_gap} threads={threads} "
        f"logfile='{log_path_opt}'"
    )
    gurobi_opts = gurobi_opts.replace('"', r'\"')
    mod_path_q = str(mod_path).replace("\\", "/")
    dat_path_q = str(dat_path).replace("\\", "/")

    script = f"""\
reset;
model '{mod_path_q}';
data '{dat_path_q}';
option solver gurobi;
option gurobi_options "{gurobi_opts}";
solve;
printf "===MILP_RESULT===\\n";
printf "STATUS: %s\\n", solve_result;
printf "OBJ: %.6g\\n", 0;
printf "N_VARS: %d\\n", _nvars;
printf "N_CONS: %d\\n", _ncons;
printf "SOLVE_TIME: %.4f\\n", _solve_time;
printf "AMPL_TIME:  %.4f\\n", _ampl_time;
printf "===END===\\n";
"""
    with open(run_path, "w") as fh:
        fh.write(script)

    print(f"[AMPL] {formulation} on {instance_name} ...")
    t0 = time.perf_counter()
    try:
        proc = subprocess.run([ampl_exe, run_path],
                              capture_output=True, text=True,
                              timeout=time_limit + 60)
        elapsed = time.perf_counter() - t0
        out = proc.stdout + proc.stderr
        returncode = proc.returncode
    except subprocess.TimeoutExpired:
        elapsed = time.perf_counter() - t0
        out = "TIMEOUT"
        returncode = None

    with open(out_path, "w") as fh:
        fh.write(out)

    parsed = parse_ampl_output(out, "MILP_RESULT")
    failure = None if parsed.get("status") else classify_ampl_failure(out, returncode)
    if failure:
        parsed["status"] = failure
    gurobi_info = parse_gurobi_log(log_path)
    solve_time = parsed.get("solve_time") or elapsed
    print(f"  status={parsed['status']}  time={solve_time:.1f}s  "
          f"nodes={gurobi_info.get('n_nodes')}")

    n_Z = n_slots * len(W)
    n_f = n_slots * dfa.n_arcs
    return ExperimentResult(
        instance_name=instance_name,
        formulation=formulation,
        n_ops=len(W),
        n_slots=n_slots,
        n_dfa_states=dfa.n_states,
        n_dfa_arcs=dfa.n_arcs,
        n_binary_vars=n_Z + n_f,
        n_constraints=parsed.get("n_cons") or 0,
        obj_value=parsed.get("obj"),
        best_bound=gurobi_info.get("best_bound"),
        gap=gurobi_info.get("gap"),
        milp_time=solve_time,
        nlp_time=None,
        total_time=solve_time,
        n_nodes=gurobi_info.get("n_nodes"),
        status=parsed.get("status") or "ampl_error",
        n_variables=parsed.get("n_vars"),
    )


